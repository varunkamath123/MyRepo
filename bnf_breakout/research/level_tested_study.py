"""Does it matter that a level has ALREADY been broken today?

    python level_tested_study.py [BNF_5MIN_DIR]

Prompted by the Oct 22 2026 trade. The strategy bought a PUT because price sat 0.009%
above the previous day's low, expecting it to break. In fact that low had ALREADY been
broken that morning (closes below it from 09:20 to 10:05), reclaimed with a +1% reversal,
and retested again at 11:45 - the "break" it anticipated had happened and failed twice.
The strategy has no memory of that: it sees only distance to the level.

The question, asked of the 420 historical sessions (the trade itself is NOT in them, so
this is a genuine test of an idea generated by one new observation):

    among the same coil-pressing-a-level setups already studied, does the outcome differ
    when the level had previously been closed through earlier the same day ("tested")
    versus never touched ("fresh")?  And does fading it ("away") beat pressing it ("toward")
    more for tested levels?

Four cells x two exit families, ALL reported (pre-registered: no cell is dropped).
Exits and costs are exactly those of breakout_study.py / breakout_study2.py.
One trigger per session per cell, so observations are independent.
"""
import math
import os
import statistics as st
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import breakout_study as B          # noqa: E402
import breakout_study2 as B2        # noqa: E402


def setup(s, i):
    """The V2 setup (coil + level press), returning (toward_direction, level_name, level_value)
    or None. Identical gating to breakout_study.trig_press(need_coil=True)."""
    px = s['C'][i]
    up, un = B.levels_above(s, i, px)
    dn, dnn = B.levels_below(s, i, px)
    du = (up - px) / px * 100 if up else 9e9
    dd = (px - dn) / px * 100 if dn else 9e9
    if min(du, dd) > B.LEVEL_PROX:
        return None
    c = s['cr'][i]
    if not (c == c) or c > s['_cr_cut']:
        return None
    return (1, un, up) if du <= dd else (-1, dnn, dn)


def was_tested(s, i, name, value, toward):
    """Had price already CLOSED through this level earlier today?"""
    if name in ('DAYH', 'DAYL'):
        return None                           # the day's own extreme cannot have been broken
    start = 6 if name in ('ORH', 'ORL') else 0
    seg = s['C'][start:i]
    if len(seg) == 0:
        return False
    return bool((seg > value).any()) if toward > 0 else bool((seg < value).any())


def stats(label, rs):
    if len(rs) < 8:
        print(f'  {label:56} n={len(rs):3}  (too few)')
        return
    n = len(rs)
    m = st.mean(rs)
    se = st.stdev(rs) / math.sqrt(n)
    h = n // 2
    print(f'  {label:56} n={n:3} mean {m:+.3f}%  CI[{m - 1.96 * se:+.3f},{m + 1.96 * se:+.3f}]'
          f'  halves {st.mean(rs[:h]):+.3f}/{st.mean(rs[h:]):+.3f}')


def main(data):
    B.DATA = data
    sessions = B.prep(B.load_sessions())
    allcr = np.concatenate([s['cr'][~np.isnan(s['cr'])] for s in sessions])
    cut = float(np.quantile(allcr, B.COIL_Q))
    for s in sessions:
        s['_cr_cut'] = cut

    cells = {}
    for group in ('tested', 'fresh'):
        trig = []
        for s in sessions:
            if s['pdh'] is None:
                continue
            for i in range(B.FIRST_BAR, min(B.LAST_BAR, s['n'] - B.HOLD_BARS - 2)):
                r = setup(s, i)
                if r is None:
                    continue
                toward, name, val = r
                t = was_tested(s, i, name, val, toward)
                if t is None:
                    continue
                if (group == 'tested') == t:
                    trig.append((s, i, toward))
                    break
        cells[group] = trig

    print('=' * 110)
    print('Was the level ALREADY broken earlier today?  (coil + level press, as in V2)')
    print('=' * 110)
    for group, trig in cells.items():
        print(f'\n  --- {group.upper()} levels: {len(trig)} sessions have such a setup ---')
        for fam, fn in (('A  stop/target/time', lambda s, i, d: B.simulate(s, i, d)[0]),
                        ('B  trailing exit   ', lambda s, i, d: B2.sim_trail(s, i, d)[0])):
            tw = [fn(s, i, d) for s, i, d in trig]
            aw = [fn(s, i, -d) for s, i, d in trig]
            stats(f'{fam}  TOWARD the level (anticipate the break)', tw)
            stats(f'{fam}  AWAY from the level (fade it)', aw)
    import random
    random.seed(11)
    base = [B.simulate(s, random.randint(B.FIRST_BAR, min(B.LAST_BAR, s['n'] - B.HOLD_BARS - 3)),
                       random.choice((1, -1)))[0] for s in sessions if s['pdh'] is not None]
    print('\n  reference:')
    stats('random bar, random direction (exit family A)', base)


if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else B.DATA)
